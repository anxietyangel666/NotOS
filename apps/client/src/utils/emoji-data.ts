function flagToCountryName(emoji: string): string | null {
  const codePoints = Array.from(emoji).map(c => c.codePointAt(0)!);
  if (codePoints.length !== 2) return null;
  const letters = codePoints.map(cp => String.fromCodePoint(cp - 0x1F1E6 + 0x41));
  const code = letters.join('');
  return COUNTRY_NAMES[code] || code;
}

export function getEmojiName(emoji: string): string {
  const registered = EMOJI_NAMES[emoji];
  if (registered) return registered;
  const flag = flagToCountryName(emoji);
  if (flag) return `flag: ${flag}`;
  return emoji;
}

