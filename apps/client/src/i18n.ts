  'РСТУФХЦЧШЩЪЫЬЭЮЯ' +
  'абвгдежзийклмноп' +
  'рстуфхцчшщъыьэюя';

const CP1251_REVERSE = new Map<string, number>(
  [...CP1251_HIGH].map((char, index) => [char, index + 0x80])
);

function decodeMojibake(value: string) {
  if (!/[РСГДОШЧЩЖНджа-я][Ѐ-ӿ]|в[Ђ-џ]|Г[^\sA-Za-z]|О[^\sA-Za-z]|Ш[^\sA-Za-z]|ж[^\sA-Za-z]|н[^\sA-Za-z]|д[^\sA-Za-z]/.test(value)) {
    return value;
  }
  const bytes: number[] = [];
  for (const char of value) {
    const code = char.charCodeAt(0);
    if (code < 0x80) bytes.push(code);
    else {
      const byte = CP1251_REVERSE.get(char);
      if (byte === undefined) return value;
      bytes.push(byte);
    }
  }
  try {
    const decoded = new TextDecoder('utf-8', { fatal: false }).decode(new Uint8Array(bytes));
    return decoded.includes('\uFFFD') ? value : decoded;
  } catch {
    return value;
  }
}

function normalizeUiText(value: string) {
  return decodeMojibake(value);
}

function normalizeTranslateLanguage(item: TranslateLanguage): TranslateLanguage {
  return { ...item, native: normalizeUiText(item.native) };
}

