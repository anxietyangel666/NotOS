export function isLanguage(value: string | null | undefined): value is Language {
  return value === 'en' || value === 'ru' || value === 'uk';
}

export function isTheme(value: string | null | undefined): value is Theme {
  return value === 'light' || value === 'dark' || value === 'system-black' || value === 'mint' || value === 'ocean';
}

export function getStoredLanguage(): Language {
  const value = localStorage.getItem(LANGUAGE_KEY);
  return isLanguage(value) ? value : 'en';
}

export function storeLanguage(language: Language) {
  localStorage.setItem(LANGUAGE_KEY, language);
}

export function getStoredTheme(): Theme {
  const value = localStorage.getItem(THEME_KEY);
  return isTheme(value) ? value : 'light';
}

export function storeTheme(theme: Theme) {
  localStorage.setItem(THEME_KEY, theme);
}

export function t(language: Language, key: TranslationKey, values: Record<string, string> = {}) {
  const template = normalizeUiText(String(translations[language][key] ?? translations.en[key]));

  return Object.entries(values).reduce((text, [name, value]) => text.split(`{${name}}`).join(value), template);
}
