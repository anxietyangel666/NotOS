export function findTranslateLanguage(code: string): TranslateLanguage | undefined {
  return TRANSLATE_LANGUAGES.find((item) => item.code === code);
}

// Language code that "Translate" in the chat message menu translates messages
// into. Defaults to the current interface language when nothing is stored yet.
export function getSavedTranslateTarget(): string {
  const value = localStorage.getItem(TRANSLATE_TARGET_KEY);
  if (value && findTranslateLanguage(value)) return value;
  return getStoredLanguage();
}

// The English language name (sent to the translation engine) for the saved
// target, falling back to English when the stored code is unknown.
export function getSavedTranslateTargetName(): string {
  return findTranslateLanguage(getSavedTranslateTarget())?.name ?? 'English';
}

export function saveTranslateTarget(code: string): void {
  localStorage.setItem(TRANSLATE_TARGET_KEY, code);
}

